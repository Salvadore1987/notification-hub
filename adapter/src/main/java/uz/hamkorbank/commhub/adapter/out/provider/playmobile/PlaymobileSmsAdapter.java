/**
 * The Playmobile SMS-Broker integration (PM-01, PM-03, §9.1, §18.1).
 *
 * <p>Primary SMS provider of the MVP. Everything provider-specific lives in this package: the request
 * shape ({@link PlaymobileSendCodec}), the error table ({@link PlaymobileErrorCatalog}) and the
 * delivery-report vocabulary ({@link PlaymobileCallbackTranslator}). Nothing above it knows Playmobile
 * exists — the router yields a {@code ProviderRef} whose {@code adapterType} is
 * {@value #ADAPTER_TYPE}, and this bean is the one that answers to it (AR-04).
 *
 * <p>What the layers below guarantee, and what this class must not repeat: timeouts, retry with
 * backoff and jitter, and the circuit breaker come from {@link ProviderCallExecutor} (PR-01); the
 * message text is already rendered and validated (SG-01 states the same for the other provider);
 * segments and cost are already computed (MP-06).
 *
 * <p>Retrying inside one delivery attempt is safe here and enabled by default, which is the one
 * behavioural difference from the SMS Gate adapter: the {@code message-id} travels with the request and
 * is generated by the Hub, so a request Playmobile received but could not acknowledge is recognised as
 * a duplicate when it arrives again (§9.1).
 */
@Component
@ConditionalOnProperty(prefix = "commhub.provider.playmobile", name = "enabled", havingValue = "true")
public class PlaymobileSmsAdapter implements SmsProviderPort {

    /** Value of {@code provider.adapter_type} this bean serves (§10.1, AR-04). */
    public static final String ADAPTER_TYPE = "playmobile-http";

    /** Reported on the ack when the Hub held the message back itself (FR-2.5). */
    public static final String THROTTLED_CODE = "THROTTLED";

    private static final int LOGGED_BODY_LENGTH = 200;

    private static final Logger LOG = LoggerFactory.getLogger(PlaymobileSmsAdapter.class);

    private final PlaymobileProperties properties;
    private final PlaymobileSendCodec codec;
    private final ProviderCallExecutor executor;
    private final ProviderThrottle throttle;
    private final ProviderMessageIdFactory providerMessageIds;
    private final SecretResolverPort secrets;
    private final ClockPort clock;
    private final RestClient client;

    public PlaymobileSmsAdapter(
            PlaymobileProperties properties,
            PlaymobileSendCodec codec,
            ProviderCallExecutor executor,
            ProviderThrottle throttle,
            ProviderMessageIdFactory providerMessageIds,
            SecretResolverPort secrets,
            ClockPort clock,
            ProviderRestClients clients) {
        this.properties = Guard.notNull(properties, "properties");
        this.codec = Guard.notNull(codec, "codec");
        this.executor = Guard.notNull(executor, "executor");
        this.throttle = Guard.notNull(throttle, "throttle");
        this.providerMessageIds = Guard.notNull(providerMessageIds, "providerMessageIds");
        this.secrets = Guard.notNull(secrets, "secrets");
        this.clock = Guard.notNull(clock, "clock");
        this.client = Guard.notNull(clients, "clients").create(properties.http());
    }

    @Override
    public AdapterType adapterType() {
        return AdapterType.of(ADAPTER_TYPE);
    }

    @Override
    public ProviderAck submit(SmsSubmission submission) {
        return submitBatch(List.of(submission)).getFirst();
    }

    /**
     * Hands a chunk to the bulk form of {@code /send} (§9.1).
     *
     * <p>Playmobile answers a bulk request as a whole: an accepted request means every message in it
     * was accepted, and a refusal refuses all of them. The answers are therefore the same verdict
     * repeated, positionally, one per submission — which is exactly the contract of the port.
     *
     * <p>Throttled messages never reach the request. Sending them and letting the provider refuse the
     * batch would take the messages that were within the limit down with them (FR-2.5).
     */
    @Override
    public List<ProviderAck> submitBatch(List<SmsSubmission> submissions) {
        if (submissions == null || submissions.isEmpty()) {
            return List.of();
        }
        List<PlaymobileSend> sends = submissions.stream()
                .map(submission -> new PlaymobileSend(submission, providerMessageIdOf(submission)))
                .toList();
        Optional<ProviderAck> throttled = throttleVerdict(sends);
        if (throttled.isPresent()) {
            return sends.stream().map(ignored -> throttled.get()).toList();
        }
        String document = codec.encode(sends, properties.sending());
        return executor.executeBatch(properties.providerCode(), properties.resilience(), sends.size(), () -> {
            ProviderAck ack = call(document, sends);
            return sends.stream().map(send -> withProviderMessageId(ack, send)).toList();
        });
    }

    /**
     * One exchange with {@code POST <base-url>/send}.
     *
     * @return the ack of an answered call
     * @throws ProviderCallException when the call had no usable answer, so retry and the breaker see it
     */
    private ProviderAck call(String document, List<PlaymobileSend> sends) {
        ProviderHttpResponse response = ProviderRestClients.send(client.post()
                .uri(PlaymobileProperties.SEND_PATH)
                .contentType(MediaType.APPLICATION_JSON)
                .header(HttpHeaders.AUTHORIZATION, basicAuth())
                .body(document));
        logExchange(response, sends);
        if (response.isSuccess()) {
            return ProviderAck.accepted(null, String.valueOf(response.status()), clock.now());
        }
        if (response.isServerError()) {
            throw ProviderCallException.retryable(
                    String.valueOf(response.status()), Masking.body(response.body(), LOGGED_BODY_LENGTH));
        }
        return refused(response);
    }

    /** An HTTP 400 carrying an {@code error_code} of §18.1 (PM-01). */
    private ProviderAck refused(ProviderHttpResponse response) {
        PlaymobileError error = codec.readError(response.body()).orElse(null);
        if (error == null) {
            throw ProviderCallException.transport(
                    "Playmobile answered %d without an error code: %s"
                            .formatted(response.status(), Masking.body(response.body(), LOGGED_BODY_LENGTH)),
                    null);
        }
        ErrorClass errorClass = PlaymobileErrorCatalog.classify(error.code());
        if (!PlaymobileErrorCatalog.isKnown(error.code())) {
            LOG.warn("Playmobile returned error code {}, which §18.1 does not list", error.code());
        }
        return switch (errorClass) {
            case BLOCKING -> throw ProviderCallException.blocking(error.code(), error.describe());
            case RETRYABLE -> throw ProviderCallException.retryable(error.code(), error.describe());
            case NON_RETRYABLE -> ProviderAck.rejected(error.code(), error.describe(), clock.now());
        };
    }

    /**
     * Stamps the id the message was sent under onto the ack.
     *
     * <p>The delivery attempt is matched to a report by this value (PM-02), so it has to reach the
     * saga even though Playmobile does not echo it: the Hub is the one that chose it.
     */
    private static ProviderAck withProviderMessageId(ProviderAck ack, PlaymobileSend send) {
        if (!ack.isAccepted()) {
            return ack;
        }
        return new ProviderAck(
                ack.result(),
                send.providerMessageId(),
                ack.providerStatus(),
                ack.responseCode(),
                ack.errorClass(),
                ack.errorDescription(),
                ack.invalidRecipient(),
                ack.respondedAt());
    }

    /** {@code <prefix><number>}, at most 20 characters, unique per sending system (§9.1). */
    private ProviderMessageId providerMessageIdOf(SmsSubmission submission) {
        return providerMessageIds.create(properties.sending().organisationPrefix(), submission.messageId());
    }

    /** Holds a chunk back when it would breach the provider's agreed rate (FR-2.5). */
    private Optional<ProviderAck> throttleVerdict(List<PlaymobileSend> sends) {
        for (PlaymobileSend send : sends) {
            Optional<String> refusal = throttle.acquire(
                    properties.providerCode(),
                    properties.rateLimit(),
                    send.submission().recipient().value());
            if (refusal.isPresent()) {
                LOG.info("Playmobile send held back: {}", refusal.get());
                // Retryable: the message must reach the next provider of the chain, not the DLQ (FR-2.2).
                return Optional.of(
                        ProviderAck.failed(THROTTLED_CODE, ErrorClass.RETRYABLE, refusal.get(), clock.now()));
            }
        }
        return Optional.empty();
    }

    /**
     * Basic auth of §9.1, rebuilt per call from the secret store.
     *
     * <p>Cheap — the resolver caches — and it is what makes a credential rotation apply without a
     * restart (SEC-04). The header value is never logged.
     */
    private String basicAuth() {
        PlaymobileProperties.Credentials credentials = properties.credentials();
        if (!credentials.isConfigured()) {
            throw ProviderCallException.blocking(
                    "NO_CREDENTIALS", "no credential references are configured for Playmobile (SEC-04)");
        }
        String pair = secrets.require(credentials.usernameRef()) + ':' + secrets.require(credentials.passwordRef());
        return "Basic " + Base64.getEncoder().encodeToString(pair.getBytes(StandardCharsets.UTF_8));
    }

    /**
     * Structured record of the exchange (PR-03).
     *
     * <p>The number is masked and the text is reduced to its length: this is the log line of an OTP
     * send, and the one thing it must never contain is the one-time password (OBS-03, SEC-06).
     */
    private static void logExchange(ProviderHttpResponse response, List<PlaymobileSend> sends) {
        PlaymobileSend first = sends.getFirst();
        if (response.isSuccess()) {
            LOG.debug(
                    "Playmobile /send accepted: messages={} firstRecipient={} messageId={} text={} status={}",
                    sends.size(),
                    Masking.msisdn(first.submission().recipient()),
                    first.providerMessageId().value(),
                    Masking.text(first.submission().content().text()),
                    response.status());
            return;
        }
        LOG.warn(
                "Playmobile /send refused: messages={} firstRecipient={} messageId={} status={} body={}",
                sends.size(),
                Masking.msisdn(first.submission().recipient()),
                first.providerMessageId().value(),
                response.status(),
                Masking.body(response.body(), LOGGED_BODY_LENGTH));
    }
}
