-- -------------------------------------------------------------------------------------
-- Сколько элементов рассылки реально загружено — против того, сколько было объявлено.
--
-- total считался сложением: заголовок объявлял expectedTotal, а каждый чанк добавлял к
-- нему свой размер. Тот, кто и объявляет, и грузит — панель (OperatorSendService) и любая
-- система-источник, честно заполнившая expectedTotal (§8.2), — удваивал собственный total.
-- Последствие не косметическое: рассылка закрывается по processed >= total, поэтому она
-- навсегда оставалась в PROCESSING, висела в batch_active_idx и показывала 50 % на карточке.
--
-- Теперь total = max(объявлено, загружено), и для этого нужно помнить загруженное отдельно.
-- Существующие строки получают 0 — «неизвестно»: их total остаётся как записан, а первый же
-- новый чанк считается верно. Счётчиком прогресса uploaded не является и в карточку не идёт.
-- -------------------------------------------------------------------------------------

ALTER TABLE batch ADD COLUMN uploaded bigint NOT NULL DEFAULT 0;

ALTER TABLE batch DROP CONSTRAINT batch_counters_ck;
ALTER TABLE batch ADD CONSTRAINT batch_counters_ck
    CHECK (total >= 0 AND uploaded >= 0 AND processed >= 0 AND sent >= 0 AND delivered >= 0 AND failed >= 0);

COMMENT ON COLUMN batch.uploaded IS
    'Загружено элементов чанками; total = max(объявлено в заголовке, загружено) (FR-1.6).';
