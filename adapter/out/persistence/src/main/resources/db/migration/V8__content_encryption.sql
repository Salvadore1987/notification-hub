-- =====================================================================================
-- V8 — шифрование контента сообщений на уровне приложения (SRS DB-04, SEC-06).
--
-- Решение: AES-256-GCM в адаптере (ContentCipher), а не pgcrypto. При pgcrypto ключ
-- пришлось бы передавать в каждом запросе — он оседает в pg_stat_statements, в логе
-- медленных запросов и в дампе трафика, и его же потребовала бы аналитическая реплика
-- (DB-06). При шифровании в приложении ключ не покидает процесс, а база — вместе с
-- бэкапами, WAL, репликой и отцепленными секциями — хранит только шифротекст.
--
-- Формат хранения: JSON-скаляр "CH1.<keyId>.<base64url(nonce‖ciphertext)>" в том же
-- jsonb-столбце. Скаляр отличим от открытого значения (объект/массив) без разбора JSON,
-- и PostgreSQL, в отличие от ключей объекта, не меняет его. Чтение принимает обе формы,
-- поэтому шифрование включается на уже наполненной базе без конвертации: старые строки
-- читаются как есть, новые и перезаписанные — уже зашифрованными.
--
-- Ключи задаются в commhub.persistence.encryption.keys (в проме — из секрет-хранилища
-- платформы); activeKeyId используется для записи, остальные остаются для чтения строк,
-- записанных до ротации, и удаляются только вместе с их секциями (DB-03).
--
-- Что НЕ шифруется и почему: message.recipient несёт обязательный GIN-индекс и поиск по
-- получателю (DB-05) — шифротекст сделал бы их невозможными; PII получателя закрыта
-- своими мерами (SHA-256 в suppression_list, маскирование в логах и UI).
--
-- Структуру таблиц миграция не меняет — типы столбцов те же; она фиксирует контракт
-- хранения в самой схеме, чтобы он был виден тому, кто читает базу без исходников.
--
-- Расширение pgcrypto из V1 остаётся установленным (полезно для разовых операций ИБ), но
-- ни шифрование контента, ни хеш адреса на нём не держатся: AddressHash считает домен.
-- =====================================================================================

COMMENT ON COLUMN message.contents IS
    'MessageContents: контент на канал (MP-02), а не один MessageContent. '
    'Шифруется приложением (AES-256-GCM, DB-04): JSON-скаляр "CH1.<keyId>.<base64url>", '
    'открытый JSON-объект — строка, записанная до включения шифрования.';

COMMENT ON COLUMN message.template_variables IS
    'Значения подстановки, из которых собран текст (FR-4.3): суммы, имена, хвост карты. '
    'Шифруется вместе с контентом (DB-04), формат тот же.';

COMMENT ON COLUMN message.recipient IS
    'Адреса получателя на канал + clientId; PII (DB-04). Намеренно не шифруется: столбец '
    'несёт GIN-индекс и поиск по получателю (DB-05). Защита — хеш в suppression_list и '
    'маскирование в логах и UI (SEC-06).';
