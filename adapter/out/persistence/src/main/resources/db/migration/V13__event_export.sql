-- =====================================================================================
-- V13 — выгрузка событий отправок в витрину данных Банка (FR-6.4).
--
-- Экспорт инкрементальный: курсор хранится рядом с сообщениями, поэтому «прочитали» и
-- «запомнили, до какого места» не могут разойтись между базами. Единица выгрузки —
-- сообщение, дошедшее до терминального статуса (§6.3), а не переход: витрина считает
-- отправки и стоимость, а поток переходов уже есть в comm.outbound.status.v1.
-- =====================================================================================

CREATE TABLE export_cursor (
    name        text        PRIMARY KEY,
    position    timestamptz NOT NULL,
    last_id     uuid,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE export_cursor IS 'Позиция инкрементальной выгрузки в витрину (FR-6.4).';
COMMENT ON COLUMN export_cursor.name IS 'Имя фида; второй потребитель заводит свою строку и идёт своим темпом.';
COMMENT ON COLUMN export_cursor.position IS 'terminal_at последнего выгруженного сообщения.';
COMMENT ON COLUMN export_cursor.last_id IS
    'id последнего выгруженного сообщения: в одну микросекунду терминальными становятся несколько,
     и курсор по одному времени либо пропускал бы их, либо повторял бесконечно.';

-- Выгрузка читает строго по этому индексу: частичный, потому что в него входят только
-- завершённые сообщения — незавершённые не раздувают выборку и не переиндексируются при
-- каждом переходе статуса.
CREATE INDEX message_export_idx ON message (terminal_at, id) WHERE terminal_at IS NOT NULL;
