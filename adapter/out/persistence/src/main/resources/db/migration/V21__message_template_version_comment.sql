-- =====================================================================================
-- V21. Комментарии к template_code / template_version_id в message.
--
-- Колонка template_version_id заведена в V4 с комментарием «заполняется со стадии
-- рендеринга (Phase 9)», но Phase 9 её так и не заполнила: версия резолвилась
-- TemplateApplier'ом, рендерила текст и выбрасывалась. Дефект найден ручным прогоном
-- (docs/testing/runs/2026-08-13-stage-1.md, D-4) и закрыт в этом же коммите.
--
-- Заодно снимается противоречие между двумя соседними комментариями V4: один говорил,
-- что сообщение ссылается на шаблон «по коду и локали, а не по id версии», второй — что
-- версия рендера хранится здесь же. Верно и то и другое, но про разные вещи: код с
-- локалью — это то, что попросил источник, а версия — то, что резолвил рендер. Пара
-- «код + локаль» ретроспективно формулировку не определяет: публикация v2 архивирует v1.
--
-- Только комментарии: структура не меняется, FK и индекс не заводятся сознательно.
-- FK ломал бы удаление версий (sql/testing/01-contour.sql переустанавливает их целиком),
-- а индекс на секционированной таблице — это индекс на каждой партиции ради запроса,
-- которого нет ни в §11.2, ни в SRS.
-- =====================================================================================

COMMENT ON COLUMN comm_hub.message.template_code IS
    'TemplateRef: то, что попросил источник — код шаблона (FR-4.1). Версию рендера см. template_version_id.';

COMMENT ON COLUMN comm_hub.message.template_version_id IS
    'Версия, которой сообщение было отрендерено (§10.1). Заполняется на стадии рендеринга; NULL у сообщения с собственным содержимым.';
