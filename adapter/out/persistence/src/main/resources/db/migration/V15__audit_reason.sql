-- -------------------------------------------------------------------------------------
-- Обоснование действия в журнале аудита (FR-7.3, ADR-0019, ADR-0038).
--
-- Панель спрашивает обоснование у девяти действий и обещает оператору, что оно попадёт
-- в журнал. До этой миграции обещание держалось наполовину: ArchiveDlq клал текст в
-- after_state, а BatchControl терял его совсем. Своя колонка — потому что «почему» это
-- не «что стало»: по ней ищут, её выгружают и она пустая у большинства записей.
-- -------------------------------------------------------------------------------------

ALTER TABLE audit_log ADD COLUMN reason text;

COMMENT ON COLUMN audit_log.reason IS
    'Обоснование, которое оператор ввёл при действии (X-Commhub-Reason, FR-7.3); NULL — действие его не требует.';
