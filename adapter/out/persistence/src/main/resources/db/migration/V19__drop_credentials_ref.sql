-- -------------------------------------------------------------------------------------
-- Ссылка на секрет уходит из конфигурации (ADR-0044).
--
-- Секреты приходят значениями свойств из переменных окружения, и разрешать в конфигурации
-- больше нечего. Эти две колонки никогда и не разрешались: креды провайдера всегда брались
-- из свойств деплоя (commhub.provider.*), а credentials_ref только записывался, читался и
-- показывался в панели.
--
-- Колонки удаляются, а не оставляются пустыми: поле, которое ничто не читает, но которое
-- панель предлагает заполнить, — это приглашение положить в базу сам секрет.
-- -------------------------------------------------------------------------------------

ALTER TABLE provider DROP COLUMN credentials_ref;
ALTER TABLE stream DROP COLUMN credentials_ref;
