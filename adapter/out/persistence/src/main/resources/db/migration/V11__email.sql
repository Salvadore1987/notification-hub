-- =====================================================================================
-- V11 — Email-канал (SRS §9.3, EM-01…EM-03).
--
-- Единственное, что каналу нужно от схемы, — вторая альтернатива тела шаблона.
-- EM-01 требует multipart/alternative, то есть у письма две формы одного текста, и
-- HTML — не отдельный шаблон, а вторая форма той же версии: у неё те же merge-поля,
-- тот же статус и тот же ревьюер (FR-4.2). Отдельная таблица развела бы их по строкам
-- и позволила бы опубликовать HTML без текста.
--
-- Разбор NDR (EM-02) своих таблиц не заводит: bounce — это отчёт о доставке, он идёт
-- тем же путём, что и DLR провайдеров (ProcessProviderStatus), а «адрес мёртв» ложится
-- в существующий suppression_list с причиной HARD_BOUNCE (FR-5.1).
-- =====================================================================================

ALTER TABLE template_version
    ADD COLUMN html_body text;

COMMENT ON COLUMN template_version.html_body IS
    'HTML-альтернатива тела письма (EM-01); NULL для SMS/Push и для писем без HTML.';

-- Текст обязателен всегда, HTML — только вместе с ним: письмо без plain-части приходит
-- пустым в клиент, который не показывает HTML, а это ровно те клиенты, ради которых
-- multipart/alternative и существует. Правило доменное (TemplateVersion.Body), здесь —
-- та же граница на стороне БД, чтобы её нельзя было обойти правкой строки руками.
ALTER TABLE template_version
    ADD CONSTRAINT template_version_html_ck CHECK (html_body IS NULL OR length(btrim(body)) > 0);
