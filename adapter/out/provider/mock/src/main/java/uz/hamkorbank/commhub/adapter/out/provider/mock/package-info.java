/**
 * Фиктивный провайдер локального стенда: отвечает вместо настоящего и никуда не отправляет
 * (ADR-0041, AR-04, QA-04).
 *
 * <p><b>Зачем.</b> До появления диспетчера вопроса «куда отправлять локально» не было: сообщения и так
 * никуда не уходили. Теперь он первый, который задаёт разработчик и дежурная смена на демонстрации, а
 * ответа в репозитории не было — WireMock в {@code docker compose} поднят, но его каталоги маппингов
 * пусты, и стенд отвечает 404 на всё. Настоящие креды локально недоступны и не должны быть доступны.
 *
 * <p><b>Правила.</b> Поведение задаётся <em>суффиксом адреса</em>, а не конфигурацией, — его видно в
 * самом тестовом номере, и не нужно лезть в настройки, чтобы понять, почему сообщение повело себя так:
 * {@code …00} — принято и затем отложенный отчёт {@code DELIVERED}; {@code …01} — принято и затем
 * {@code UNDELIVERED}; {@code …02} — ответа нет, то есть бросок, ретрай и failover (PR-01);
 * {@code …03} — блокирующий отказ, breaker открывается сразу, как на Playmobile 102; {@code …04} —
 * постоянный отказ «адрес непригоден», регистрируется suppression (FR-5.1); всё остальное — принято и
 * {@code DELIVERED}.
 *
 * <p><b>Контракт фазы 7 соблюдается буквально</b>: любой ответ — это {@code ProviderAck}, отсутствие
 * ответа — исключение. Именно поэтому мок полезен, а не декоративен: без броска на {@code …02} он не
 * воспроизводил бы ни ретрай, ни failover, ни breaker.
 *
 * <p><b>Выключен по умолчанию.</b> {@code commhub.provider.mock.enabled} без {@code matchIfMissing}:
 * в собранном образе бины не создаются. Включается корневым {@code config/application.yml}, который не
 * попадает ни в jar, ни в образ, и требует профиля провайдера с типом адаптера {@code mock-sms} —
 * а профили живут в базе, то есть на боевом контуре его пришлось бы ещё и завести руками.
 */
